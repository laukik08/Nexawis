import type { ReportRecord } from '../types/reports';

/**
 * Sanitizes a field for safe CSV output and mitigates Spreadsheet Formula Injection (CWE-1236)
 */
function sanitizeCsvCell(val: string | number | undefined | null): string {
  if (val === undefined || val === null) return '""';
  let str = String(val);
  // Mitigate CSV Formula Injection by prepending single quote if starting with formula triggers
  if (/^[=+\-@\t\r]/.test(str)) {
    str = `'${str}`;
  }
  const escaped = str.replace(/"/g, '""');
  return `"${escaped}"`;
}

/**
 * Triggers a browser download of a CSV file
 */
function triggerCsvDownload(csvContent: string, filename: string) {
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', filename.endsWith('.csv') ? filename : `${filename}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Export an individual report's data to CSV
 */
export function exportReportToCsv(report: ReportRecord) {
  const timestamp = new Date().toISOString().slice(0, 10);
  const safeTitle = report.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
  const filename = `${report.id.toLowerCase()}_${safeTitle}_${timestamp}.csv`;

  const lines: string[] = [];

  // Header metadata
  lines.push(`"NEXAWIS Intelligence Report: ${report.name.replace(/"/g, '""')}"`);
  lines.push(`"Report ID:","${report.id}"`);
  lines.push(`"Category:","${report.category}"`);
  lines.push(`"Period:","${report.reportingPeriod}"`);
  lines.push(`"Generated At:","${report.createdAt}"`);
  lines.push(`"Generated By:","${report.createdBy}"`);
  lines.push(`"Notice:","Demonstration report data for frontend evaluation"`);
  lines.push('');

  // Key Summary Metrics
  lines.push('"--- EXECUTIVE SUMMARY METRICS ---"');
  lines.push('"Metric","Value","Unit","Change / Trend","Benchmark"');
  report.summaryMetrics.forEach(m => {
    lines.push([
      sanitizeCsvCell(m.label),
      sanitizeCsvCell(m.value),
      sanitizeCsvCell(m.unit || ''),
      sanitizeCsvCell(m.change || ''),
      sanitizeCsvCell(m.benchmark || '')
    ].join(','));
  });
  lines.push('');

  // Primary Table Data if available
  if (report.tableData && report.tableData.headers.length > 0) {
    lines.push(`"--- ${report.tableData.title.toUpperCase()} ---"`);
    lines.push(report.tableData.headers.map(sanitizeCsvCell).join(','));
    report.tableData.rows.forEach(row => {
      lines.push(row.map(sanitizeCsvCell).join(','));
    });
    lines.push('');
  }

  // Key Findings
  if (report.findings && report.findings.length > 0) {
    lines.push('"--- KEY OBSERVATIONS & FINDINGS ---"');
    report.findings.forEach((finding, idx) => {
      lines.push(`"${idx + 1}.","${finding.replace(/"/g, '""')}"`);
    });
    lines.push('');
  }

  // Insights
  if (report.insights && report.insights.length > 0) {
    lines.push('"--- ACTIONABLE INSIGHTS ---"');
    lines.push('"Title","Observation","Metric"');
    report.insights.forEach(ins => {
      lines.push([
        sanitizeCsvCell(ins.title),
        sanitizeCsvCell(ins.observation),
        sanitizeCsvCell(ins.metric)
      ].join(','));
    });
  }

  const csvContent = lines.join('\r\n');
  triggerCsvDownload(csvContent, filename);
}

/**
 * Export the report library summary table to CSV
 */
export function exportReportLibraryToCsv(reports: ReportRecord[]) {
  const timestamp = new Date().toISOString().slice(0, 10);
  const filename = `nexawis_reports_library_${timestamp}.csv`;

  const headers = [
    'Report ID',
    'Report Name',
    'Category',
    'Reporting Period',
    'Created At',
    'Created By',
    'Status',
    'Format'
  ];

  const rows = reports.map(r => [
    r.id,
    r.name,
    r.category,
    r.reportingPeriod,
    r.createdAt,
    r.createdBy,
    r.status,
    r.format
  ]);

  const lines = [
    headers.map(sanitizeCsvCell).join(','),
    ...rows.map(row => row.map(sanitizeCsvCell).join(','))
  ];

  triggerCsvDownload(lines.join('\r\n'), filename);
}

