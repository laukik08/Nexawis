"""
NEXAWIS Backend - PDF Report Export Engine.
Generates structured, multi-page vector PDF reports using ReportLab with running
headers, dynamic page numbering ("Page X of Y"), metric cards, styled tables,
and governance disclaimers.
"""

import io
from typing import Any, Dict, List, Optional
from datetime import datetime, timezone

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    KeepTogether,
    HRFlowable,
)
from reportlab.pdfgen import canvas


class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas that dynamically calculates the total page count
    and renders running headers and 'Page X of Y' footers.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(36, 806, "NEXAWIS Enterprise Reporting — Confidential")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(36, 800, 559, 800)

        # Running Footer (all pages)
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(36, 42, 559, 42)

        self.drawString(36, 30, "Generated by NEXAWIS Autonomous Workforce Intelligence System")
        page_str = f"Page {self._pageNumber} of {total_pages}"
        self.drawRightString(559, 30, page_str)

        self.restoreState()


def generate_report_pdf(report: Dict[str, Any], workspace_name: str = "NEXAWIS Workspace") -> bytes:
    """
    Generates a professional, selectable PDF document for the given report dataset.
    Returns the binary content of the PDF.
    """
    buffer = io.BytesIO()

    # Printable width: 595.27 - 72 = 523.27 pt
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=36,
        rightMargin=36,
        topMargin=54,
        bottomMargin=54,
        title=report.get("name") or "NEXAWIS Report",
        author="NEXAWIS Autonomous System",
    )

    styles = getSampleStyleSheet()

    # Custom Typography Palette
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#0F172A"),
        spaceAfter=4,
    )

    badge_style = ParagraphStyle(
        "BadgeText",
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#0284C7"),
    )

    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#64748B"),
    )

    section_heading = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#0F172A"),
        spaceBefore=12,
        spaceAfter=6,
    )

    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#334155"),
    )

    bullet_style = ParagraphStyle(
        "BulletItem",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=12,
        textColor=colors.HexColor("#334155"),
        leftIndent=12,
        spaceAfter=3,
    )

    table_header_style = ParagraphStyle(
        "TableHeader",
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.white,
    )

    table_cell_style = ParagraphStyle(
        "TableCell",
        fontName="Helvetica",
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#1E293B"),
    )

    table_cell_bold = ParagraphStyle(
        "TableCellBold",
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#0F172A"),
    )

    callout_style = ParagraphStyle(
        "CalloutText",
        fontName="Helvetica",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#475569"),
    )

    story = []

    # 1. Header Banner Block
    report_title = report.get("name") or report.get("title") or "NEXAWIS Intelligence Report"
    category = report.get("category", "executive")
    category_label = category.replace("_", " ").title()
    period = report.get("reportingPeriod", "Last 30 Days")
    created_at = report.get("createdAt") or datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    config = report.get("config", {})
    if hasattr(config, "model_dump"):
        config = config.model_dump()
    elif not isinstance(config, dict):
        config = {}
    dept = config.get("department", "All")
    proj_id = config.get("projectId", "All")

    story.append(Paragraph(f"<b>NEXAWIS INTELLIGENCE</b> &bull; {category_label.upper()}", badge_style))
    story.append(Spacer(1, 4))
    story.append(Paragraph(report_title, title_style))

    meta_text = (
        f"<b>Workspace:</b> {workspace_name} &nbsp;&bull;&nbsp; "
        f"<b>Reporting Window:</b> {period} &nbsp;&bull;&nbsp; "
        f"<b>Department:</b> {dept} &nbsp;&bull;&nbsp; "
        f"<b>Project:</b> {proj_id} &nbsp;&bull;&nbsp; "
        f"<b>Generated:</b> {created_at}"
    )
    story.append(Paragraph(meta_text, subtitle_style))
    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#E2E8F0"), spaceAfter=12))

    # 2. Executive Summary Metrics Grid
    summary_metrics: List[Dict[str, Any]] = report.get("summaryMetrics") or []
    if summary_metrics:
        story.append(Paragraph("Executive Summary Metrics", section_heading))

        metric_cells = []
        for m in summary_metrics[:4]:
            val_str = f"{m.get('value', '—')}"
            if m.get("unit"):
                val_str += f" {m.get('unit')}"
            
            sub_str = m.get("change") or m.get("benchmark") or ""

            cell_content = [
                Paragraph(m.get("label", "").upper(), ParagraphStyle("MLabel", fontName="Helvetica-Bold", fontSize=7, leading=9, textColor=colors.HexColor("#64748B"))),
                Spacer(1, 2),
                Paragraph(val_str, ParagraphStyle("MVal", fontName="Helvetica-Bold", fontSize=14, leading=16, textColor=colors.HexColor("#0284C7"))),
                Spacer(1, 1),
                Paragraph(sub_str, ParagraphStyle("MSub", fontName="Helvetica", fontSize=7, leading=9, textColor=colors.HexColor("#16A34A") if m.get("status") == "positive" else colors.HexColor("#64748B"))),
            ]
            metric_cells.append(cell_content)

        # Pad to 4 cells if needed
        while len(metric_cells) < 4:
            metric_cells.append([Paragraph("", body_style)])

        kpi_table = Table(
            [[metric_cells[0], metric_cells[1], metric_cells[2], metric_cells[3]]],
            colWidths=[130, 130, 130, 130],
        )
        kpi_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ("TOPPADDING", (0, 0), (-1, -1), 8),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ("RIGHTPADDING", (0, 0), (-1, -1), 10),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]))
        story.append(kpi_table)
        story.append(Spacer(1, 14))

    # 3. Detailed Data Table
    table_data = report.get("tableData")
    if table_data and table_data.get("headers"):
        t_title = table_data.get("title") or "Detailed Telemetry"
        story.append(Paragraph(t_title, section_heading))

        headers = table_data.get("headers", [])
        raw_rows = table_data.get("rows", [])

        # Build table cells with autowrap
        header_cells = [Paragraph(f"<b>{h}</b>", table_header_style) for h in headers]
        table_rows = [header_cells]

        if raw_rows:
            for r_idx, row in enumerate(raw_rows[:40]):  # Cap to first 40 rows per page constraints
                row_cells = []
                for c_idx, val in enumerate(row):
                    style = table_cell_bold if c_idx == 0 else table_cell_style
                    row_cells.append(Paragraph(str(val if val is not None else "—"), style))
                table_rows.append(row_cells)
        else:
            table_rows.append([Paragraph("<i>No records match active parameters.</i>", table_cell_style)] + [Paragraph("", table_cell_style)] * (len(headers) - 1))

        # Dynamically compute column widths to fit 520pt printable width
        num_cols = len(headers)
        col_width = 520.0 / max(1, num_cols)
        col_widths = [col_width] * num_cols

        data_table = Table(table_rows, colWidths=col_widths, repeatRows=1)
        data_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0F172A")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("BOTTOMPADDING", (0, 0), (-1, 0), 5),
            ("TOPPADDING", (0, 0), (-1, 0), 5),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ("TOPPADDING", (0, 1), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 1), (-1, -1), 4),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        story.append(data_table)
        story.append(Spacer(1, 14))

    # 4. Key Observations & Findings
    findings: List[str] = report.get("findings") or []
    if findings:
        findings_elements = [Paragraph("Key Observations & Diagnostic Findings", section_heading)]
        for f in findings:
            findings_elements.append(Paragraph(f"&bull;&nbsp;&nbsp;{f}", bullet_style))
        story.append(KeepTogether(findings_elements))
        story.append(Spacer(1, 10))

    # 5. Governance Warnings & Capacity Alerts
    warnings: List[str] = report.get("warnings") or []
    if warnings:
        warn_elements = [Paragraph("Capacity & Governance Alerts", section_heading)]
        for w in warnings:
            warn_elements.append(Paragraph(f"<b>[ALERT]</b>&nbsp;&nbsp;{w}", ParagraphStyle("WarnItem", parent=bullet_style, textColor=colors.HexColor("#B45309"))))
        story.append(KeepTogether(warn_elements))
        story.append(Spacer(1, 10))

    # 6. Actionable Insights
    insights: List[Dict[str, Any]] = report.get("insights") or []
    if insights:
        insight_elements = [Paragraph("Actionable Recommendations", section_heading)]
        for ins in insights:
            prio = ins.get("priority", "info").upper()
            title = ins.get("title", "Insight")
            obs = ins.get("observation", "")
            metric = ins.get("metric", "")
            text = f"<b>[{prio}] {title}</b> ({metric}) &mdash; {obs}"
            insight_elements.append(Paragraph(text, bullet_style))
        story.append(KeepTogether(insight_elements))
        story.append(Spacer(1, 12))

    # 7. Operational & Ethical Disclaimers
    disclaimer_elements = [
        HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#CBD5E1"), spaceAfter=8),
        Paragraph("<b>ETHICS & OPERATIONAL GOVERNANCE DISCLOSURE</b>", ParagraphStyle("DiscHead", fontName="Helvetica-Bold", fontSize=7.5, leading=10, textColor=colors.HexColor("#475569"))),
    ]
    if category == "sustainability":
        disclaimer_elements.append(Paragraph(
            "<b>Operational Heuristic Note:</b> Workforce sustainability indices and burnout indicators are capacity governance heuristics designed for managerial rebalancing under NEXAWIS policy. They do not constitute clinical or medical diagnoses.",
            callout_style
        ))
    elif category in ("executive", "projects"):
        disclaimer_elements.append(Paragraph(
            "<b>ML Model Provenance:</b> Prospective project delivery predictions reflect statistical estimations evaluated against historical training corpora. They are not certified contract deliverables and should be cross-referenced with team lead reviews.",
            callout_style
        ))
    else:
        disclaimer_elements.append(Paragraph(
            "This document is an authorized snapshot generated from verified workspace database records. Distribution is restricted to authorized personnel.",
            callout_style
        ))

    story.append(KeepTogether(disclaimer_elements))

    # Build document
    doc.build(story, canvasmaker=NumberedCanvas)
    buffer.seek(0)
    return buffer.getvalue()
