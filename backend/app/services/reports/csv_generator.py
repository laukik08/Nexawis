"""
NEXAWIS Backend - CSV Report Export Engine.
Produces structured, standards-compliant UTF-8 CSV exports with robust spreadsheet
formula injection mitigation (CWE-1236) and clean sectional layouts.
"""

import io
import csv
from typing import Any, Dict, List, Optional
from datetime import datetime, timezone


def sanitize_csv_cell(val: Any) -> str:
    """
    Sanitizes string cells to mitigate Spreadsheet Formula Injection (CSV Injection, CWE-1236).
    Prepends a single quote (') if the text begins with dangerous command characters
    (=, +, -, @, tab, or carriage return).
    """
    if val is None:
        return ""
    text_val = str(val)
    if not text_val:
        return ""
    if text_val[0] in ("=", "+", "-", "@", "\t", "\r"):
        return f"'{text_val}"
    return text_val


def generate_report_csv(report: Dict[str, Any], workspace_name: str = "NEXAWIS Workspace") -> bytes:
    """
    Renders a complete, structured CSV export from persisted report data.
    Encoded as UTF-8 with BOM (utf-8-sig) for native Microsoft Excel and LibreOffice support.
    """
    output = io.StringIO()
    writer = csv.writer(output, quoting=csv.QUOTE_MINIMAL)

    # 1. Header Metadata Block
    report_title = report.get("name") or report.get("title") or "NEXAWIS Intelligence Report"
    category = report.get("category", "General")
    period = report.get("reportingPeriod", "Active Window")
    created_at = report.get("createdAt") or datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    created_by = report.get("createdBy", "Authorized User")
    config = report.get("config", {})
    if hasattr(config, "model_dump"):
        config = config.model_dump()
    elif not isinstance(config, dict):
        config = {}
    dept = config.get("department", "All")
    proj_id = config.get("projectId", "All")

    writer.writerow(["NEXAWIS ENTERPRISE INTELLIGENCE REPORT"])
    writer.writerow(["Report Name", sanitize_csv_cell(report_title)])
    writer.writerow(["Category", sanitize_csv_cell(category.replace("_", " ").title())])
    writer.writerow(["Reporting Period", sanitize_csv_cell(period)])
    writer.writerow(["Workspace", sanitize_csv_cell(workspace_name)])
    writer.writerow(["Department Filter", sanitize_csv_cell(dept)])
    writer.writerow(["Project Filter", sanitize_csv_cell(proj_id)])
    writer.writerow(["Generated At", sanitize_csv_cell(created_at)])
    writer.writerow(["Generated By", sanitize_csv_cell(created_by)])
    writer.writerow(["Data Provenance", "Live workspace database records"])
    writer.writerow([])

    # 2. Executive Summary Metrics
    summary_metrics: List[Dict[str, Any]] = report.get("summaryMetrics") or []
    if summary_metrics:
        writer.writerow(["--- EXECUTIVE SUMMARY METRICS ---"])
        writer.writerow(["Metric", "Value", "Unit", "Change / Benchmark", "Status"])
        for m in summary_metrics:
            writer.writerow([
                sanitize_csv_cell(m.get("label", "")),
                sanitize_csv_cell(m.get("value", "")),
                sanitize_csv_cell(m.get("unit", "")),
                sanitize_csv_cell(m.get("change") or m.get("benchmark") or "Standard"),
                sanitize_csv_cell(m.get("status", "neutral").upper()),
            ])
        writer.writerow([])

    # 3. Detailed Data Table
    table_data = report.get("tableData")
    if table_data and table_data.get("headers"):
        t_title = table_data.get("title") or "Detailed Telemetry"
        writer.writerow([f"--- {t_title.upper()} ---"])
        headers = [sanitize_csv_cell(h) for h in table_data.get("headers", [])]
        writer.writerow(headers)

        rows = table_data.get("rows", [])
        if rows:
            for row in rows:
                writer.writerow([sanitize_csv_cell(cell) for cell in row])
        else:
            writer.writerow(["(No records matching selected filters)"])
        writer.writerow([])

    # 4. Key Findings & Observations
    findings: List[str] = report.get("findings") or []
    if findings:
        writer.writerow(["--- KEY OBSERVATIONS & FINDINGS ---"])
        for idx, f in enumerate(findings, 1):
            writer.writerow([f"{idx}.", sanitize_csv_cell(f)])
        writer.writerow([])

    # 5. Warnings & Capacity Alerts
    warnings: List[str] = report.get("warnings") or []
    if warnings:
        writer.writerow(["--- GOVERNANCE & DATA QUALITY WARNINGS ---"])
        for idx, w in enumerate(warnings, 1):
            writer.writerow([f"WARNING {idx}:", sanitize_csv_cell(w)])
        writer.writerow([])

    # 6. Actionable Insights
    insights: List[Dict[str, Any]] = report.get("insights") or []
    if insights:
        writer.writerow(["--- ACTIONABLE RECOMMENDATIONS ---"])
        writer.writerow(["Title", "Observation", "Metric Impact", "Priority"])
        for ins in insights:
            writer.writerow([
                sanitize_csv_cell(ins.get("title", "")),
                sanitize_csv_cell(ins.get("observation", "")),
                sanitize_csv_cell(ins.get("metric", "")),
                sanitize_csv_cell(ins.get("priority", "info").upper()),
            ])
        writer.writerow([])

    # 7. Disclaimers & Operational Notes
    writer.writerow(["--- ETHICS & OPERATIONAL GOVERNANCE NOTES ---"])
    if category == "sustainability":
        writer.writerow([
            "Operational Heuristic Notice",
            "Burnout risk indices and sustainability scores are operational capacity heuristics for workload rebalancing, not psychological or clinical diagnoses."
        ])
    elif category in ("executive", "projects"):
        writer.writerow([
            "ML Provenance Notice",
            "Prospective project simulations reflect statistical estimations based on historical training corpora and must not be treated as certified future deliverables."
        ])
    writer.writerow([
        "Confidentiality Notice",
        "This document contains proprietary enterprise workforce intelligence. Distribution is restricted to authorized workspace personnel."
    ])

    csv_text = output.getvalue()
    # Encode with UTF-8 BOM for seamless Microsoft Excel compatibility
    return csv_text.encode("utf-8-sig")
